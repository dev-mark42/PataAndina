'use strict';
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '..');
const guest = fs.readFileSync(path.join(root, 'js/guest.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'invitado.html'), 'utf8');
const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
const sql = fs.readFileSync(path.join(root, 'supabase/INSTALACION_LIMPIA_COMPLETA.sql'), 'utf8');
const ids = [...sql.matchAll(/^\('([^']+)','/gm)].map(m => m[1]);

assert(html.includes('./js/guest.js'), 'invitado.html carga guest.js');
assert(html.includes('id="gPane"'), 'existe el contenedor del catálogo');
assert(!html.includes('gTabs'), 'invitado no presenta pestañas de otras funciones');
assert(index.includes('./invitado.html'), 'login enlaza al modo invitado');
assert(guest.includes(".from('services_catalog')"), 'invitado consulta el catálogo');
assert(!/\\.from\\(['"](profiles|pets|appointment_requests|pet_medical_records|audit_events)['"]\\)/.test(guest), 'invitado no consulta tablas privadas');
assert(!/sb\\.auth\\./.test(guest), 'invitado no llama a Supabase Auth');
assert(guest.includes('data-login-action') && guest.includes("const loginUrl = './index.html'"), 'acciones llevan al login');
assert(app.includes("if (!session) return location.replace('./index.html')"), 'app privada exige sesión');
assert(sw.includes("'./invitado.html'"), 'PWA precarga la ruta invitado');
assert(ids.length === 50 && new Set(ids).size === 50, 'SQL inserta 50 servicios con IDs únicos');
assert(sql.includes('generate_series(1,200)'), 'SQL crea 200 eventos demo');
assert(sql.includes('15 mascotas') && sql.includes('Kira'), 'SQL incluye 15 mascotas demo');
assert(sql.includes('create table if not exists public.pet_vaccinations'), 'SQL incluye tabla de vacunas');
assert(sql.includes('create table if not exists public.pet_deworming'), 'SQL incluye tabla de desparasitación');
assert(app.includes('logoTapCount >= 8') && app.includes("go('avances')"), 'Avances se desbloquean con ocho toques al logo');
assert(app.includes("from('pet_vaccinations')") && app.includes("from('pet_deworming')"), 'Historial muestra vacunas y desparasitación');
assert(sql.includes('delete from public.appointment_requests') && sql.includes('delete from public.profiles'), 'SQL limpia datos operativos');
assert(sql.includes('create policy services_select on public.services_catalog for select to anon, authenticated'), 'anon solo tiene política pública de servicios');
assert(sql.includes('revoke all on public.profiles, public.pets, public.services_catalog,'), 'SQL revoca permisos previos');
console.log('OK: invitado solo consulta servicios, acciones van al login, app privada exige sesión, PWA incluye la ruta y SQL contiene 50 servicios únicos + 200 eventos.');
